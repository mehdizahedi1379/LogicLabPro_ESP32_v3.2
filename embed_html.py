#!/usr/bin/env python3
"""
HTML -> index_html.h (gzip + PROGMEM)

استفاده:
    python3 tools/embed_html.py                      # webapp/logiclab_pro_v2.html -> index_html.h
    python3 tools/embed_html.py my.html out.h        # مسیرهای دلخواه

بعد از هر تغییر در فایل HTML این اسکریپت را اجرا کنید و اسکچ را دوباره روی ESP32 آپلود کنید.
"""
import gzip, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "webapp" / "logiclab_pro_v2.html"
dst = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "index_html.h"

raw = src.read_bytes()
gz = gzip.compress(raw, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(gz), 16):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]))

dst.write_text(
    "// AUTO-GENERATED by tools/embed_html.py -- do not edit by hand.\n"
    f"// Source: {src.name}  ({len(raw)} bytes raw, {len(gz)} bytes gzip)\n"
    "#pragma once\n#include <Arduino.h>\n\n"
    f"const size_t INDEX_HTML_GZ_LEN = {len(gz)};\n"
    "const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n" + ",\n".join(lines) + "\n};\n"
)
print(f"{src.name}: {len(raw)} -> {len(gz)} bytes (gzip), wrote {dst}")
